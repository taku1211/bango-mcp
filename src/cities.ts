/** 「大阪市」「27100」「２７１００」を5桁コードにする。解釈できなければ null。 */
export function toCityCode(input: string): string | null {
  const s = input.normalize("NFKC").trim().replace(/\s+/g, "");
  if (/^\d{5}$/.test(s)) return s;
  if (/^\d{6}$/.test(s)) return s.slice(0, 5); // 検査数字付き6桁
  const name = s.replace(/^(東京都|北海道|(?:京都|大阪)府|.{2,3}県)/, "");
  return DESIGNATED_CITIES[name] ?? DESIGNATED_CITIES[`${name}市`] ?? null;
}
